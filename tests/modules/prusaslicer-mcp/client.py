"""Slice a local cube through the installed MCP server without a printer or GUI."""

import json
import os
from pathlib import Path
import select
import subprocess
import sys
import time


class Client:
    def __init__(self, command):
        self.log = open("mcp-server.log", "ab")
        self.child = subprocess.Popen(
            command, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=self.log
        )
        self.buffer = bytearray()
        self.identifier = 0

    def send(self, value):
        self.child.stdin.write(json.dumps(value).encode() + b"\n")
        self.child.stdin.flush()

    def request(self, method, params):
        self.identifier += 1
        identifier = self.identifier
        self.send({"jsonrpc": "2.0", "id": identifier, "method": method, "params": params})
        deadline = time.monotonic() + 120
        while True:
            while b"\n" not in self.buffer:
                remaining = deadline - time.monotonic()
                assert remaining > 0 and select.select(
                    [self.child.stdout], [], [], remaining
                )[0], f"MCP timeout: {method}"
                chunk = os.read(self.child.stdout.fileno(), 65536)
                assert chunk, f"MCP server exited: {self.child.poll()}"
                self.buffer.extend(chunk)
            line, _, rest = self.buffer.partition(b"\n")
            self.buffer[:] = rest
            reply = json.loads(line)
            if reply.get("id") == identifier:
                assert "error" not in reply, reply
                return reply["result"]

    def close(self):
        self.child.terminate()
        try:
            self.child.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self.child.kill()
            self.child.wait()
        self.log.close()


connection = json.loads(subprocess.check_output(["codex", "mcp", "get", "prusaslicer", "--json"]))
assert connection["enabled"] is True
transport = connection["transport"]
os.environ.update(transport["env"])
assert os.environ["MCP_TRANSPORT"] == "stdio"
assert os.environ["SLICER_TYPE"] == "prusaslicer"
assert not os.environ.get("DISPLAY")
assert not os.environ.get("API_KEY")

# A closed, outward-facing 10 mm cube, independent of network fixtures.
vertices = [(0, 0, 0), (10, 0, 0), (10, 10, 0), (0, 10, 0),
            (0, 0, 10), (10, 0, 10), (10, 10, 10), (0, 10, 10)]
faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7),
         (0, 1, 5), (0, 5, 4), (1, 2, 6), (1, 6, 5),
         (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
stl = Path("cube.stl").resolve()
with stl.open("w") as stream:
    stream.write("solid cube\n")
    for face in faces:
        stream.write("facet normal 0 0 0\nouter loop\n")
        for index in face:
            stream.write("vertex %s %s %s\n" % vertices[index])
        stream.write("endloop\nendfacet\n")
    stream.write("endsolid cube\n")
profile = Path("test.ini").resolve()
profile.write_text("""printer_technology = FFF
nozzle_diameter = 0.4
filament_diameter = 1.75
filament_density = 1.24
layer_height = 0.2
first_layer_height = 0.2
fill_density = 20%
bed_shape = 0x0,200x0,200x200,0x200
temperature = 205
first_layer_temperature = 205
bed_temperature = 60
first_layer_bed_temperature = 60
gcode_flavor = marlin
""")
client = Client([transport["command"], *transport.get("args", [])])
try:
    client.request("initialize", {
        "protocolVersion": "2025-03-26", "capabilities": {},
        "clientInfo": {"name": "prusaslicer-mcp-integration", "version": "1"},
    })
    client.send({"jsonrpc": "2.0", "method": "notifications/initialized"})
    tools = {tool["name"] for tool in client.request("tools/list", {})["tools"]}
    assert "slice_stl" in tools, tools
    result = client.request("tools/call", {
        "name": "slice_stl", "arguments": {
            "stl_path": str(stl), "slicer_profile": str(profile),
        },
    })
    assert not result.get("isError"), result
    print(json.dumps(result))
    # Validate the retained slicer's output, not merely a successful MCP reply.
    output = Path(result["structuredContent"]["path"])
    assert output.is_absolute() and output.is_file(), result
    assert result["content"] == [{"type": "text", "text": str(output)}], result
    gcode = output.read_text()
    assert "generated by PrusaSlicer" in gcode
    assert "G1 " in gcode and " E" in gcode
    assert "; temperature = 205" in gcode and "filament used [mm]" in gcode
    Path("slice-result.gcode").write_text(gcode)
finally:
    client.close()
